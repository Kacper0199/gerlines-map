import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { load } from "js-yaml";
import { type BodyRow, bodyTable, type SeriesRow } from "../src/cars/identical-body-rules.ts";

const USAGE = `usage: node apps/web/scripts/build-identical-bodies.ts

Reads catalog/identical-bodies.yaml and catalog/vehicle-series.yaml and writes
apps/web/src/cars/identical-bodies.generated.ts; run biome format on it afterwards.`;

if (process.argv.includes("--help")) {
  process.stdout.write(`${USAGE}\n`);
  process.exit(0);
}

const root = resolve(import.meta.dirname, "../../..");
const read = (name: string) => load(readFileSync(resolve(root, "catalog", name), "utf8"));
const table = bodyTable(
  read("identical-bodies.yaml") as BodyRow[],
  read("vehicle-series.yaml") as SeriesRow[],
);
const body = Object.entries(table)
  .map(([id, relation]) => `  ${JSON.stringify(id)}: ${JSON.stringify(relation)},`)
  .join("\n");
writeFileSync(
  resolve(root, "apps/web/src/cars/identical-bodies.generated.ts"),
  `import type { BodyTable } from "./identical-body-rules.ts";\n\n/** The accepted rows of catalog/identical-bodies.yaml. Generated by scripts/build-identical-bodies.ts. */\nexport const IDENTICAL_BODY_TABLE: BodyTable = {${body ? `\n${body}\n` : ""}};\n`,
);
process.stdout.write(`${Object.keys(table).length} accepted pairs\n`);
