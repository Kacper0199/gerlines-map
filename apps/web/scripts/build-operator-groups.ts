import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { load } from "js-yaml";
import { groupTable, type OperatorRow } from "../src/modes/operator-group-rules.ts";

const USAGE = `usage: node apps/web/scripts/build-operator-groups.ts

Reads catalog/operators.yaml and writes apps/web/src/modes/operator-groups.generated.ts;
run biome format on it afterwards.`;

if (process.argv.includes("--help")) {
  process.stdout.write(`${USAGE}\n`);
  process.exit(0);
}

const root = resolve(import.meta.dirname, "../../..");
const rows = load(readFileSync(resolve(root, "catalog/operators.yaml"), "utf8")) as OperatorRow[];
const table = groupTable(rows);
const body = Object.entries(table)
  .map(([id, group]) => `  ${JSON.stringify(id)}: ${JSON.stringify(group)},`)
  .join("\n");
writeFileSync(
  resolve(root, "apps/web/src/modes/operator-groups.generated.ts"),
  `import type { ColouredGroup } from "./operator-group-list.ts";\n\n/** The group of every operator of catalog/operators.yaml. Generated by scripts/build-operator-groups.ts. */\nexport const OPERATOR_GROUP_TABLE: Readonly<Record<string, ColouredGroup | "other">> = {\n${body}\n};\n`,
);
process.stdout.write(`${rows.length} operators\n`);
