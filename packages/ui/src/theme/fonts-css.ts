export interface FontFamilySource {
  readonly family: "Overpass" | "Overpass Mono";
  readonly packageName: "overpass" | "overpass-mono";
  readonly weights: readonly number[];
}

export const FONT_SOURCES: readonly FontFamilySource[] = [
  { family: "Overpass", packageName: "overpass", weights: [400, 600, 800] },
  { family: "Overpass Mono", packageName: "overpass-mono", weights: [400, 600] },
];

export const KEPT_SUBSETS: readonly string[] = ["latin-ext", "latin"];

const FACE = /\/\* (\S+)-(\d+)-normal \*\/\s*@font-face\s*\{([^}]*)\}/g;
const UNICODE_RANGE = /unicode-range:\s*([^;]+);/;

export interface FontFace {
  readonly subset: string;
  readonly weight: number;
  readonly unicodeRange: string;
}

export function parseFontsourceFaces(css: string, packageName: string): FontFace[] {
  const faces: FontFace[] = [];
  for (const match of css.matchAll(FACE)) {
    const [, name, weight, body] = match;
    const range = UNICODE_RANGE.exec(body ?? "")?.[1];
    if (name?.startsWith(`${packageName}-`) && weight && range) {
      faces.push({
        subset: name.slice(packageName.length + 1),
        weight: Number(weight),
        unicodeRange: range.trim(),
      });
    }
  }
  return faces;
}

function faceCss(source: FontFamilySource, face: FontFace): string {
  const file = `${source.packageName}-${face.subset}-${face.weight}-normal.woff2`;
  return [
    "@font-face {",
    `  font-family: "${source.family}";`,
    "  font-style: normal;",
    "  font-display: swap;",
    `  font-weight: ${face.weight};`,
    `  src: url("../../node_modules/@fontsource/${source.packageName}/files/${file}") format("woff2");`,
    `  unicode-range: ${face.unicodeRange};`,
    "}",
  ].join("\n");
}

export function fontsCss(readWeightCss: (packageName: string, weight: number) => string): string {
  const blocks: string[] = [
    "/* Generated by scripts/generate-theme.ts from the @fontsource packages. Do not edit by hand. */",
    "/* Fontsource subset files carry no unicode-range, so the faces are rebuilt from the per-weight files. */",
  ];
  for (const source of FONT_SOURCES) {
    for (const weight of source.weights) {
      const faces = parseFontsourceFaces(
        readWeightCss(source.packageName, weight),
        source.packageName,
      ).filter((face) => KEPT_SUBSETS.includes(face.subset));
      for (const subset of KEPT_SUBSETS) {
        const face = faces.find((candidate) => candidate.subset === subset);
        if (!face) {
          throw new Error(`${source.packageName} ${weight} has no ${subset} face`);
        }
        blocks.push(faceCss(source, face));
      }
    }
  }
  return `${blocks.join("\n\n")}\n`;
}
