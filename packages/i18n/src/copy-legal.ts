export type LegalCopy = ReturnType<typeof createLegalCopy>;

export type LegalPageCopy = Omit<Copy, "legal"> & { readonly legal: LegalCopy };

const cache = new Map<Locale, LegalPageCopy>();

/** The whole copy with the legal block in full, for the legal and credits pages. */
export function legalCopyFor(locale: Locale): LegalPageCopy {
  const cached = cache.get(locale);
  if (cached !== undefined) {
    return cached;
  }
  const created = { ...copyFor(locale), legal: createLegalCopy(locale) };
  cache.set(locale, created);
  return created;
}
