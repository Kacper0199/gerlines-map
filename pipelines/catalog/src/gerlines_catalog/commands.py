APPLICATION = f"gerlines-catalog/{__version__}"


def _print(data: object) -> None:
    sys.stdout.write(json.dumps(data, indent=2, ensure_ascii=False, default=str) + "\n")


def validate(catalog_dir: Path) -> int:
    try:
        catalog = read_catalog(catalog_dir)
    except SeedError as error:
        sys.stderr.write(f"{error}\n")
        return 1
    _print({"valid": True, "content_sha256": catalog.content_sha256, "rows": catalog.counts()})
    return 0


def load(catalog_dir: Path, database_url: str, dry_run: bool) -> int:
    try:
        catalog = read_catalog(catalog_dir)
    except SeedError as error:
        sys.stderr.write(f"{error}\n")
        return 1
    with psycopg.connect(database_url, application_name=APPLICATION) as conn:
        result = loader.load(conn, catalog)
        conflicts = result["alias_conflicts"] != 0
        if dry_run or conflicts:
            conn.rollback()
        result["committed"] = not (dry_run or conflicts)
        if dry_run:
            result["dry_run"] = True
    _print(result)
    return 3 if conflicts else 0


def fingerprint(database_url: str) -> int:
    with psycopg.connect(database_url, application_name=APPLICATION) as conn:
        conn.read_only = True
        _print(fingerprints(conn))
    return 0


def coverage_report(
    catalog_dir: Path, feed_url: str, day: str, feed_version: int, out: Path | None
) -> int:
    catalog = read_catalog(catalog_dir)
    with psycopg.connect(feed_url, application_name=APPLICATION) as conn:
        conn.read_only = True
        result = coverage.report(catalog, conn, feed_version, date.fromisoformat(day))
    if out:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n")
    _print(result)
    return 0


def line_colours(cache: ResearchCache, catalog_dir: Path, out: Path) -> int:
    body = upstream.fetch(cache, upstream.LINE_COLOURS).body.decode("utf-8")
    operators = yaml.safe_load((catalog_dir / "operators.yaml").read_text(encoding="utf-8"))
    known = {row["operator_id"] for row in operators}
    rows, skipped = build.line_colour_rows(body, known, upstream.LINE_COLOURS.key)
    out.write_text(build.write_line_colours(rows), encoding="utf-8")
    _print({"written": len(rows), "skipped": dict(skipped), "file": str(out)})
    return 0


def verbuende(cache: ResearchCache, out: Path) -> int:
    page = fetch_pages(cache, [build.VERBUND_LIST_TITLE])[build.VERBUND_LIST_TITLE]
    titles = build.verbund_article_titles(page)
    qids = build.resolve_articles(cache, titles)
    websites = build.item_websites(cache, qids.values())
    rows = build.verbund_rows(page, qids, websites, build.absent_articles(cache, titles))
    header = (
        f"# Generated by `gerlines-catalog verbuende` from {page.permalink}\n"
        "# (CC BY-SA 4.0) and Wikidata (CC0) for wikidata_qid and website. Do not edit by hand.\n"
    )
    text = yaml.safe_dump(rows, allow_unicode=True, sort_keys=False, width=100)
    out.write_text(header + text, encoding="utf-8")
    _print({"written": len(rows), "revision": page.revid, "file": str(out)})
    return 0


class _NoAliases(yaml.SafeDumper):
    def ignore_aliases(self, data: object) -> bool:
        return True


def fleet_ice_lines(
    cache: ResearchCache, catalog_dir: Path, source_id: str, valid_from: date, valid_to: date
) -> int:
    page = fetch_pages(cache, [fleet.ICE_LIST_TITLE])[fleet.ICE_LIST_TITLE]
    urls = {s.source_id: str(s.homepage_url) for s in read_catalog(catalog_dir).sources}
    problem = fleet.cited_revision_problem(source_id, urls.get(source_id), page.revid)
    if problem:
        sys.stderr.write(f"{problem}\n")
        return 1
    rows = fleet.ice_line_rules(page.wikitext, source_id, valid_from, valid_to)
    sys.stdout.write(f"# from {page.permalink}\n")
    sys.stdout.write(
        yaml.dump(rows, Dumper=_NoAliases, allow_unicode=True, sort_keys=False, width=100)
    )
    return 0


def series_class_report(cache: ResearchCache, catalog_dir: Path, out: Path | None) -> int:
    """Derive unit kind, traction and double deck from Wikidata; fail on seeds that disagree."""
    catalog = read_catalog(catalog_dir)
    qids = [s.wikidata_qid for s in catalog.vehicle_series if s.wikidata_qid]
    derived = {
        qid: series_classes.derive(entry)
        for qid, entry in series_classes.fetch(cache, qids).items()
    }
    report = {
        s.series_id: {
            "wikidata_qid": s.wikidata_qid,
            "values": derived[s.wikidata_qid].values,
            "evidence": derived[s.wikidata_qid].evidence,
            "reasons": derived[s.wikidata_qid].reasons,
        }
        for s in catalog.vehicle_series
        if s.wikidata_qid in derived
    }
    problems = series_classes.disagreements(catalog.vehicle_series, derived)
    if out:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
    _print({"series": len(report), "disagreements": problems})
    return 1 if problems else 0


GENERATED_SECTION = "# ---- Layer L2, IC, Railjet and regional lines (generated)"
NEXT_SECTION = "# ---- Layer L3"


def fleet_section(
    generated: fleet_lists.Generated, command: str, feed: fleet_lists.FeedFile
) -> str:
    """The generated block of fleet-rules.yaml: a header naming the command and the timetable
    file it read, then the rules."""
    exceptions = (
        ", ".join(
            f"list {e.list} line {e.line} from {e.floor}" for e in fleet_lists.MATCH_EXCEPTIONS
        )
        or "none"
    )
    header = [
        GENERATED_SECTION,
        f"# Generated by `{command}`,",
        f"# where <id> is the feed version of the {feed.source_id} timetable file {feed.name}",
        f"# (published {feed.published_on}, sha256 {feed.sha256}) in the database read;",
        "# do not edit by hand. Rows of the cited revisions (sources.yaml) of the IC line list,",
        "# the Intercity 2 article (table of lines in service), the ICE line list (its Railjet",
        "# and ECE lines run as ld) and the Länder line lists, matched to the timetable pairs",
        "# (operator, category, line) of that day. evidence is adapted from the article (CC BY-SA",
        "# 4.0, Wikipedia contributors): markup and references removed, the lines of a cell joined",
        "# with semicolons, rows joined with a bar. A row naming a vehicle the catalogue lacks",
        "# gets no rule. match_share is the share of the pair's trips that start or end at a",
        f"# station of the row's route; a rule needs {fleet_lists.MATCH_SHARE_FLOOR}",
        f"# (exceptions: {exceptions}).",
        "# An IC2 of the IC lists is the Twindexx Intercity 2 because the IC list says DB sold its",
        "# KISS to ÖBB in June 2025; the command stops when the cited revision no longer says so.",
    ]
    body = yaml.dump(
        generated.rules, Dumper=_NoAliases, allow_unicode=True, sort_keys=False, width=100,
        default_flow_style=None,
    )  # fmt: skip
    return "\n".join(header) + "\n" + body


def replace_fleet_section(text: str, section: str) -> str:
    start = text.index(GENERATED_SECTION)
    end = text.index(NEXT_SECTION, start)
    return text[:start] + section + "\n" + text[end:]


def _cited_oldids(catalog_dir: Path) -> dict[str, int]:
    urls = {s.source_id: str(s.homepage_url) for s in read_catalog(catalog_dir).sources}
    found: dict[str, int] = {}
    for spec in fleet_lists.LINE_LISTS:
        url = urls.get(spec.source_id)
        match = re.search(r"[?&]oldid=(\d+)", url or "")
        if match is None:
            msg = f"{spec.source_id} ({spec.title}) cites no oldid in sources.yaml: {url}"
            raise SeedError(msg)
        found[spec.short] = int(match.group(1))
    return found


def fleet_ic_regional_lines(  # noqa: PLR0913
    cache: ResearchCache,
    catalog_dir: Path,
    feed_url: str,
    *,
    day: date,
    feed_version: int,
    valid: tuple[date, date],
    write: bool,
    report: Path | None,
    refresh: bool = False,
) -> int:
    oldids = _cited_oldids(catalog_dir)
    revisions = fetch_revisions(cache, list(oldids.values()), refresh=refresh)
    missing = sorted(short for short, oldid in oldids.items() if oldid not in revisions)
    if missing:
        sys.stderr.write(f"revisions not returned for: {', '.join(missing)}\n")
        return 1
    pages = {short: revisions[oldid].wikitext for short, oldid in oldids.items()}
    with psycopg.connect(feed_url, application_name=APPLICATION) as conn:
        conn.read_only = True
        feed = fleet_lists.feed_file(conn, feed_version)
        if feed is None:
            sys.stderr.write(f"feed version {feed_version} is not a loaded feed version\n")
            return 1
        if not feed.covers(day):
            sys.stderr.write(
                f"{day} is outside {feed.name} ({feed.valid_from} to {feed.valid_to})\n"
            )
            return 1
        timetable = fleet_lists.timetable_pairs(conn, feed_version, day)
    series = yaml.safe_load((catalog_dir / "vehicle-series.yaml").read_text(encoding="utf-8"))
    operators = yaml.safe_load((catalog_dir / "operators.yaml").read_text(encoding="utf-8"))
    generated = fleet_lists.build_rules(
        pages, timetable, Catalogue.of(series), fleet_lists.OperatorIndex.of(operators), valid
    )
    command = (
        f"gerlines-catalog fleet-ic-regional-lines --day {day} --feed-version <id>"
        f" --valid-from {valid[0]} --valid-to {valid[1]} --write"
    )
    section = fleet_section(generated, command, feed)
    path = catalog_dir / "fleet-rules.yaml"
    if write:
        path.write_text(replace_fleet_section(path.read_text(encoding="utf-8"), section), "utf-8")
    else:
        sys.stdout.write(section)
    summary = {
        "rules": len(generated.rules),
        "by_category": dict(Counter(str(r["category"]) for r in generated.rules)),
        "skipped": dict(Counter(s.reason.split(":")[0] for s in generated.skipped)),
        "revisions": oldids,
        "feed": {"name": feed.name, "sha256": feed.sha256},
        "timetable_pairs": len(timetable),
    }
    if report:
        report.parent.mkdir(parents=True, exist_ok=True)
        detail = {**summary, "skipped_rows": [asdict(s) for s in generated.skipped]}
        report.write_text(json.dumps(detail, indent=1, ensure_ascii=False) + "\n")
    sys.stderr.write(json.dumps(summary, ensure_ascii=False) + "\n")
    return 0
